"""Generated headers, version information and manifests for the native Windows executables."""
import hashlib
from pathlib import Path, PurePosixPath
import re
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
NATIVE_SOURCES = [ROOT / "launcher" / "native.c", ROOT / "launcher" / "archive_check.c"]
RUNTIME_SOURCES = [*NATIVE_SOURCES, ROOT / "launcher" / "runtime.c"]
COMPANY = "DekuForge contributors"
COPYRIGHT = "Copyright (c) 2026 BrutusBossNL. MIT License."
DEVELOPMENT_RUNTIME = "development-interpreter"
_IDENTITY = re.compile(r"[A-Za-z0-9.-]+")
_VERSION = re.compile(r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?")
_DIGEST = re.compile(r"[0-9a-f]{64}")
_URL = re.compile(r"https://[A-Za-z0-9.-]+/[A-Za-z0-9/._%+~-]+")
_CACHE_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._+-]*")


def _pin(entry, label):
    url, digest, size = entry.get("url", ""), entry.get("sha256", ""), entry.get("size")
    if not _URL.fullmatch(url) or not _DIGEST.fullmatch(digest):
        raise ValueError(f"Invalid {label} download pin")
    if not isinstance(size, int) or isinstance(size, bool) or not 0 < size <= 100 * 1024**2:
        raise ValueError(f"Invalid {label} download size")
    name = unquote(PurePosixPath(urlsplit(url).path).name)
    if not _CACHE_NAME.fullmatch(name) or name.endswith(".") or ".." in name:
        raise ValueError(f"Invalid {label} download file name")
    return url, digest, size, name


def runtime_pin_header(components):
    """C defines for the pinned runtime; every value is validated before it becomes a literal."""
    launcher, python = components["launcher"]["version"], components["python"]
    identity = python["id"]
    if not _IDENTITY.fullmatch(identity) or not _VERSION.fullmatch(launcher):
        raise ValueError("Invalid runtime or launcher component identity")
    lines = [f'#define DEKU_PYTHON_ID L"{identity}"', f'#define DEKU_LAUNCHER_VERSION L"{launcher}"']
    if identity == DEVELOPMENT_RUNTIME:
        values = {"PYTHON": ("", "0" * 64, 0, ""), "PILLOW": ("", "0" * 64, 0, "")}
        version, source = "development", "development"
    else:
        if python.get("source") != "astral-python-build-standalone":
            raise ValueError("Unsupported launcher runtime provider")
        values = {"PYTHON": _pin(python, "runtime"), "PILLOW": _pin(python["pillow"], "Pillow")}
        version, source = python["version"], python["source"]
        if not _VERSION.fullmatch(version):
            raise ValueError("Invalid runtime version")
    lines += [f'#define DEKU_PYTHON_VERSION "{version}"', f'#define DEKU_RUNTIME_SOURCE "{source}"']
    for prefix, (url, digest, size, name) in values.items():
        lines += [f'#define DEKU_{prefix}_URL L"{url}"', f'#define DEKU_{prefix}_SHA256 "{digest}"',
                  f"#define DEKU_{prefix}_SIZE {size}ULL", f'#define DEKU_{prefix}_CACHE L"{name}"']
    return "// Generated from dekuforge/components.json by tools/native_resources.py.\n" + "\n".join(lines) + "\n"


def digest_header(name, digest):
    if not re.fullmatch(r"DEKU_[A-Z0-9_]+", name) or not _DIGEST.fullmatch(digest):
        raise ValueError("Invalid digest header")
    return f'// Generated by the DekuForge build.\n#define {name} "{digest}"\n'


def packaged_sha256(path):
    """Digest of a source file as the launcher package stores it (LF line endings)."""
    return hashlib.sha256(Path(path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def _numeric(version):
    parts = version.split("-", 1)[0].split(".")
    if len(parts) != 3 or not all(part.isdigit() and int(part) < 65536 for part in parts):
        raise ValueError("Invalid numeric file version")
    return [*parts, "0"]


def _rc_path(path):
    text = Path(path).resolve().as_posix()
    if '"' in text:
        raise ValueError("Resource path cannot be quoted")
    return text


def write_resources(output, stem, *, description, filename, version, icon, extra=()):
    """Write `<stem>.rc` with icon, complete version information and an asInvoker manifest."""
    if not _VERSION.fullmatch(version) or not re.fullmatch(r"[A-Za-z0-9 .-]+", description) \
            or not re.fullmatch(r"[A-Za-z0-9-]+\.exe", filename):
        raise ValueError("Invalid executable resource metadata")
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    numeric = _numeric(version)
    manifest = output / f"{stem}.manifest"
    manifest.write_text(f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <assemblyIdentity type="win32" name="DekuForge.{filename[:-4].replace("-", ".")}" version="{".".join(numeric)}" processorArchitecture="amd64"/>
  <description>{description}</description>
  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">
    <security>
      <requestedPrivileges>
        <requestedExecutionLevel level="asInvoker" uiAccess="false"/>
      </requestedPrivileges>
    </security>
  </trustInfo>
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <supportedOS Id="{{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}}"/>
    </application>
  </compatibility>
</assembly>
''', encoding="utf-8")
    strings = {"CompanyName": COMPANY, "FileDescription": description, "FileVersion": version,
               "InternalName": filename[:-4], "LegalCopyright": COPYRIGHT, "OriginalFilename": filename,
               "ProductName": "DekuForge", "ProductVersion": version}
    values = "\n".join(f'   VALUE "{key}", "{value}\\0"' for key, value in strings.items())
    resource = output / f"{stem}.rc"
    resource.write_text(f'''101 ICON "{_rc_path(icon)}"
1 24 "{_rc_path(manifest)}"
{chr(10).join(extra)}
1 VERSIONINFO
FILEVERSION {",".join(numeric)}
PRODUCTVERSION {",".join(numeric)}
FILEOS 0x40004
FILETYPE 0x1
BEGIN
 BLOCK "StringFileInfo"
 BEGIN
  BLOCK "040904b0"
  BEGIN
{values}
  END
 END
 BLOCK "VarFileInfo"
 BEGIN
  VALUE "Translation", 0x409, 1200
 END
END
''', encoding="utf-8")
    return resource
